import '../../domain/entities/early_warning_entity.dart';

class EarlyWarningModel extends EarlyWarningEntity {
  const EarlyWarningModel({
    required super.id,
    required super.title,
    required super.district,
    required super.state,
    required super.severity,
    required super.riskScore,
    required super.confidence,
    required super.validUntil,
    required super.advisory,
    required super.evacuationRoute,
    required super.affectedSectors,
    required super.createdAt,
    super.isActive = true,
    super.isRead = false,
  });

  factory EarlyWarningModel.fromJson(Map<String, dynamic> json) {
    return EarlyWarningModel(
      id: json['id'] as String? ?? 'WARN-2026-001',
      title: json['title'] as String? ?? 'Disaster Warning',
      district: json['district'] as String? ?? 'Tawang',
      state: json['state'] as String? ?? 'Arunachal Pradesh',
      severity: json['severity'] as String? ?? 'HIGH',
      riskScore: json['risk_score'] as int? ?? 80,
      confidence: (json['confidence'] as num?)?.toDouble() ?? 0.90,
      validUntil: json['valid_until'] as String? ?? 'Next 24 Hours',
      advisory: json['advisory'] as String? ?? '',
      evacuationRoute: json['evacuation_route'] as String? ?? 'Main Highway corridor',
      affectedSectors: (json['affected_sectors'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
      createdAt: json['created_at'] as String? ?? 'Just now',
      isActive: json['is_active'] as bool? ?? true,
      isRead: json['is_read'] as bool? ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'district': district,
      'state': state,
      'severity': severity,
      'risk_score': riskScore,
      'confidence': confidence,
      'valid_until': validUntil,
      'advisory': advisory,
      'evacuation_route': evacuationRoute,
      'affected_sectors': affectedSectors,
      'created_at': createdAt,
      'is_active': isActive,
      'is_read': isRead,
    };
  }

